def replace_section(text: str, section_name: str, new_body: str) -> str:
    pattern = re.compile(rf"(?ms)^## {re.escape(section_name)}\s*\n(.*?)(?=^## |\Z)")
    match = pattern.search(text)
    if not match:
        raise ValueError(f"Section not found: {section_name}")
    replacement = f"## {section_name}\n{new_body.strip()}\n\n"
    return text[: match.start()] + replacement + text[match.end() :]


def process_file(problem_md: Path) -> None:
    text = problem_md.read_text(encoding="utf-8")
    problem_id = problem_md.parent.name

    if problem_id in QUESTION_OVERRIDES:
        text = replace_section(text, "Q", QUESTION_OVERRIDES[problem_id])

    if problem_id in SOLUTION_OVERRIDES:
        text = replace_section(text, "Solution", SOLUTION_OVERRIDES[problem_id])

    problem_md.write_text(text.rstrip() + "\n", encoding="utf-8")


def main() -> None:
    for problem_md in sorted(PROBLEM_ROOT.glob("*/problem.md")):
        if not problem_md.parent.name.startswith(TARGET_PREFIXES):
            continue
        process_file(problem_md)


if __name__ == "__main__":
    main()

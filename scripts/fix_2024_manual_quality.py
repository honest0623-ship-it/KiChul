def replace_section(text: str, name: str, body: str) -> str:
    pattern = rf"(?ms)^##\s*{re.escape(name)}\s*\n.*?(?=^##\s|\Z)"
    replacement = f"## {name}\n{body.strip()}\n\n"
    out, n = re.subn(pattern, lambda _m: replacement, text)
    if n == 0:
        raise RuntimeError(f"Section not found: {name}")
    return out


def main() -> None:
    for pid, values in DATA.items():
        path = ROOT / pid / "problem.md"
        text = path.read_text(encoding="utf-8")
        text = replace_section(text, "Q", values["Q"])
        if "Choices" in values:
            text = replace_section(text, "Choices", values["Choices"])
        text = replace_section(text, "Solution", values["Solution"])
        path.write_text(text, encoding="utf-8")
    print(f"updated {len(DATA)} files")


if __name__ == "__main__":
    main()
